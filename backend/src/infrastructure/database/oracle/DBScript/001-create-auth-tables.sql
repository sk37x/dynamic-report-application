CREATE TABLE AUTH_SESSIONS (
    SESSION_ID          VARCHAR2(36 BYTE) NOT NULL,
    USER_ID             NVARCHAR2(200) NOT NULL,
    REFRESH_TOKEN_HASH  RAW(32) NOT NULL,
    EXPIRES_AT_MS       NUMBER(16, 0) NOT NULL,
    REVOKED_AT_MS       NUMBER(16, 0),

    CONSTRAINT PK_AUTH_SESSIONS
        PRIMARY KEY (SESSION_ID)
);

CREATE INDEX IX_AUTH_SESSIONS_EXPIRY
    ON AUTH_SESSIONS (EXPIRES_AT_MS);


CREATE TABLE AUTH_USERS (
    USER_ID       VARCHAR2(36 BYTE) NOT NULL,
    USERNAME      VARCHAR2(100 BYTE) NOT NULL,
    DISPLAY_NAME  NVARCHAR2(200) NOT NULL,
    PASSWORD_HASH VARCHAR2(200 BYTE) NOT NULL,
    IS_ACTIVE     NUMBER(1, 0) DEFAULT 1 NOT NULL,

    CONSTRAINT PK_AUTH_USERS
        PRIMARY KEY (USER_ID),

    CONSTRAINT UQ_AUTH_USERS_USERNAME
        UNIQUE (USERNAME),

    CONSTRAINT CK_AUTH_USERS_ACTIVE
        CHECK (IS_ACTIVE IN (0, 1))
);